package com.example.timeapp.data.db

import android.content.Context
import androidx.room.Database
import androidx.room.Room
import androidx.room.RoomDatabase
import androidx.room.TypeConverters
import com.example.timeapp.data.SampleData

@Database(
    entities = [
        EntryEntity::class,
        ScheduleBlockEntity::class,
        WalletEntity::class,
        MoneyRecordEntity::class,
        IdeaCollectionEntity::class,
        IdeaEntity::class,
        AchievementEntity::class,
        BookmarkEntity::class,
        WorkSessionEntity::class,
        SubtaskEntity::class,
        WorkdaySegmentEntity::class,
        ReviewEntity::class,
        ReminderEntity::class,
        CategoryEntity::class,
        HabitEntity::class,
        HabitCheckEntity::class,
        TagEntity::class,
        EntryTagEntity::class,
        EntryEventEntity::class,
        TaskDependencyEntity::class,
        BoardColumnEntity::class,
        TaskBookmarkEntity::class,
        SavingsGoalEntity::class,
        GoalAllocationEntity::class,
        UtilityTimerEntity::class,
        WorkTargetEntity::class,
        FocusRuntimeEntity::class,
        SessionCorrectionEntity::class,
        TimerPresetEntity::class,
        CommitmentEntity::class,
        LoanEntity::class,
        AttachmentEntity::class,
        InboxItemEntity::class,
    ],
    version = DB_VERSION,
    exportSchema = true,
)
@TypeConverters(Converters::class)
abstract class TimeDatabase : RoomDatabase() {
    abstract fun entryDao(): EntryDao
    abstract fun walletDao(): WalletDao
    abstract fun moneyRecordDao(): MoneyRecordDao
    abstract fun ideaCollectionDao(): IdeaCollectionDao
    abstract fun ideaDao(): IdeaDao
    abstract fun achievementDao(): AchievementDao
    abstract fun bookmarkDao(): BookmarkDao
    abstract fun workSessionDao(): WorkSessionDao
    abstract fun subtaskDao(): SubtaskDao
    abstract fun workdaySegmentDao(): WorkdaySegmentDao
    abstract fun reviewDao(): ReviewDao
    abstract fun reminderDao(): ReminderDao
    abstract fun categoryDao(): CategoryDao
    abstract fun habitDao(): HabitDao
    abstract fun tagDao(): TagDao
    abstract fun entryEventDao(): EntryEventDao
    abstract fun dependencyDao(): DependencyDao
    abstract fun boardColumnDao(): BoardColumnDao
    abstract fun taskBookmarkDao(): TaskBookmarkDao
    abstract fun savingsDao(): SavingsDao
    abstract fun utilityTimerDao(): UtilityTimerDao
    abstract fun workTargetDao(): WorkTargetDao
    abstract fun focusDao(): FocusDao
    abstract fun commitmentDao(): CommitmentDao
    abstract fun loanDao(): LoanDao
    abstract fun attachmentDao(): AttachmentDao
    abstract fun scheduleBlockDao(): ScheduleBlockDao
    abstract fun inboxDao(): InboxDao

    /** Creates the default Board columns when there are none — scaffolding, like categories. */
    suspend fun ensureBoardColumns() {
        if (boardColumnDao().all().isNotEmpty()) return
        com.example.timeapp.data.DefaultBoardColumns.forEachIndexed { i, (name, status) ->
            boardColumnDao().insert(BoardColumnEntity(name = name, status = status, sortOrder = i))
        }
    }

    /**
     * Loads the demo content on demand — never automatically, so a new install is empty.
     * No-ops when anything already exists, so it can't duplicate a real user's records.
     * Insertion order matters: it fixes the autogenerated ids later rows reference.
     */
    suspend fun seedIfEmpty() {
        if (walletDao().count() > 0) return

        SampleData.wallets.forEach { walletDao().insert(it.toEntity()) }
        SampleData.entries.forEach { entryDao().insert(it.toEntity()) }
        SampleData.plans.forEach { moneyRecordDao().insert(it.toEntity()) }
        SampleData.history.forEach { moneyRecordDao().insert(it.toEntity()) }
        // Sparks and the Bucket list already exist (they're scaffolding, created at start), so
        // the demo's own copies map onto them instead of clashing on their fixed ids.
        val collectionIds = SampleData.ideaCollections.associate { demo ->
            demo.id to (ideaCollectionDao().firstOfKind(demo.kind)?.takeIf { demo.kind != com.example.timeapp.data.CollectionKind.LIST }?.id
                ?: ideaCollectionDao().insert(demo.toEntity().copy(id = 0)))
        }
        (SampleData.recentlyTouched + SampleData.bucketOpen + SampleData.bucketDone).forEach { idea ->
            ideaDao().insert(idea.toEntity().copy(id = 0, collectionId = collectionIds[idea.collectionId] ?: idea.collectionId))
        }
        SampleData.bookmarks.forEach { bookmarkDao().insert(it.toEntity()) }
    }

    /** Wipes every record but keeps preferences and the app lock — "delete all data" in the
     * PDF's sense, not a factory reset. Callers must cancel pending reminder alarms first,
     * since those live outside the database. */
    suspend fun clearAllRecords() {
        clearAllTables()
        // Scaffolding comes straight back: without this, every category picker and the Board
        // stayed empty after "Delete all data" until the app was restarted.
        com.example.timeapp.data.repository.CategoryRepository(this).ensureDefaults()
        com.example.timeapp.data.repository.IdeaRepository(ideaCollectionDao(), ideaDao()).ensureDefaults()
        ensureBoardColumns()
    }

    companion object {
        @Volatile private var instance: TimeDatabase? = null
        const val FILE_NAME = "time.db"

        fun getInstance(context: Context): TimeDatabase =
            instance ?: synchronized(this) {
                instance ?: Room.databaseBuilder(context.applicationContext, TimeDatabase::class.java, FILE_NAME)
                    // Real migrations from 13 on — see Migrations.kt. Only development
                    // builds older than 13 (before any data was worth keeping) still wipe.
                    .addMigrations(*ALL_MIGRATIONS)
                    .fallbackToDestructiveMigrationFrom(true, *(1..12).toList().toIntArray())
                    .build()
                    .also { instance = it }
            }

        /** Restore-only escape hatch: closes and drops the singleton so the on-disk file can
         * be safely replaced. Never call this for any other reason — every repository built
         * in `TimeNavHost.kt` captures `database` by value at construction time, so nothing
         * observes this happening; the caller must restart the process afterward. */
        fun clearInstanceForRestore() {
            synchronized(this) {
                instance?.close()
                instance = null
            }
        }
    }
}
