"""Regenerates app/src/main/java/com/example/timeapp/data/BnStrings.kt from the code and bn.tsv.

Run from the repository root:  python3 tools/i18n/build_catalog.py
It lists every English text in the code that has no Bangla yet (MISSING) and every translation
whose %N$s slots don't match its English (PROBLEM) — fix those in bn.tsv and run it again.
Texts that must stay English (search keywords, date patterns, ids) are listed in KEEP_ENGLISH.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'app/src/main/java/com/example/timeapp')
OUT = os.path.join(SRC, 'data/BnStrings.kt')
TSV = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'bn.tsv')
KEEP_ENGLISH = {'day off', 'home screen', 'do not disturb', 'lock screen', 'material you', 'long break',
                'auto start', 'time format', 'date format', 'Asia/Dhaka', 'no stream', 'd MMM', 'd MMM yyyy'}
# Passed to L as values at runtime (enum labels), so the scan below can't see them.
RUNTIME_KEYS = ['Violet', 'Ink & Orange', 'Cyan & Amber', 'Forest & Coral', 'Navy & Lime']

def unesc_kotlin(k):
    return k.replace('\\$', '$').replace('\\"', '"').replace('\\n', '\n').replace('\\\\', '\\')

def keys_in_code():
    pat = re.compile(r'(?<![A-Za-z0-9_])L\("((?:[^"\\]|\\.)*)"')
    seen, keys = set(), []
    for dp, dn, fn in sorted(os.walk(SRC)):
        for f in sorted(fn):
            if not f.endswith('.kt') or f == 'BnStrings.kt':
                continue
            for m in pat.finditer(open(os.path.join(dp, f), encoding='utf-8').read()):
                k = unesc_kotlin(m.group(1))
                if k not in seen:
                    seen.add(k); keys.append(k)
    for k in RUNTIME_KEYS:
        if k not in seen:
            keys.append(k)
    return keys

def load_tsv():
    tr = {}
    for line in open(TSV, encoding='utf-8').read().split('\n'):
        if not line or line.startswith('#') or '\t' not in line:
            continue
        k, t = line.split('\t', 1)
        un = lambda s: s.replace('\\n', '\n').replace('\\t', '\t').replace('\\\\', '\\')
        tr[un(k)] = un(t)
    return tr

def main():
    keys, tr = keys_in_code(), load_tsv()
    pairs, bad = [], 0
    for k in keys:
        if k in KEEP_ENGLISH:
            continue
        if k not in tr:
            print('MISSING', repr(k)); bad += 1; continue
        t = tr[k].strip(' ')
        if k.startswith(' '): t = ' ' + t
        if k.endswith(' '): t = t + ' '
        if sorted(re.findall(r'%\d+\$s', k)) != sorted(re.findall(r'%\d+\$s', t)):
            print('PROBLEM', repr(k), '->', repr(t)); bad += 1; continue
        pairs.append((k, t))
    kt = lambda s: '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$').replace('\n', '\\n') + '"'
    lines = ['package com.example.timeapp.data', '', '/**',
             ' * Bangla for every English text passed to [L] (Phase 17). GENERATED by',
             ' * tools/i18n/build_catalog.py from tools/i18n/bn.tsv — edit the TSV, not this file.',
             ' * Keyed by the exact English wording; `%1$s`-style slots keep their numbers so a sentence',
             ' * can reorder them. Anything missing here shows in English.', ' */',
             'object BnStrings {', '    val map: Map<String, String> = hashMapOf(']
    lines += [f'        {kt(k)} to {kt(t)},' for k, t in pairs]
    lines += ['    )', '}', '']
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines))
    print(f'{len(pairs)} translated, {bad} to fix; wrote {os.path.relpath(OUT, ROOT)}')
    sys.exit(1 if bad else 0)

if __name__ == '__main__':
    main()
